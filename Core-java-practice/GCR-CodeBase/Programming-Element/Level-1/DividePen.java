public class DividePen {
  public static void main(String[] args) {
      int totalPen = 14;
      int student = 3;

      int DividedPen = totalPen / student;

      int remaning = totalPen % student;

      System.out.println("The Pen Per Student is " + DividedPen +" and the remaining pen not distributed is " + remaning);
  }
}
